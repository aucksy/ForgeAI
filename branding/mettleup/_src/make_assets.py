def superellipse(cx, cy, r, k=3.2, steps=160):
    import math
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        c, s = math.cos(t), math.sin(t)
        pts.append((cx + r * (abs(c) ** (2 / k)) * (1 if c >= 0 else -1),
                    cy + r * (abs(s) ** (2 / k)) * (1 if s >= 0 else -1)))
    return poly(pts)


def mask_icon_svg(shape, themed=False):
    """The adaptive icon as a launcher draws it at 48 dp: 72 dp of the 108 dp layers, masked."""
    clip = {'circle': '<circle cx="54" cy="54" r="36"/>',
            'squircle': f'<path d="{superellipse(54, 54, 36)}"/>',
            'rounded': '<rect x="18" y="18" width="72" height="72" rx="18"/>'}[shape]
    if themed:
        layers = ('<rect width="108" height="108" fill="#D8E2FF"/>'
                  + B.mark(54, 54, ADAPT_R, 'th' + shape, mode='mono', colour='#2B4678'))
    else:
        layers = f'<rect width="108" height="108" fill="{B.STEEL}"/>' + B.mark(54, 54, ADAPT_R, 'ms' + shape)
    return B.svg(72, 72, f'<defs><clipPath id="c">{clip}</clipPath></defs><g clip-path="url(#c)">{layers}</g>',
                 vb='18 18 72 72')



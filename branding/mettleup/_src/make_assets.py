def tile_svg(size, shape='square', bleed=False):
    """Steel tile + mark. bleed: full square (Play/iOS round it themselves)."""
    s = size
    if bleed:
        tile = f'<rect width="{s}" height="{s}" fill="{B.STEEL}"/>'
        vis = s
    elif shape == 'round':
        tile = f'<circle cx="{s / 2}" cy="{s / 2}" r="{n(s * 22 / 48)}" fill="{B.STEEL}"/>'
        vis = s * 44 / 48
    else:
        m = s * 2 / 48
        tile = (f'<rect x="{n(m)}" y="{n(m)}" width="{n(s - 2 * m)}" height="{n(s - 2 * m)}" '
                f'rx="{n(s * 9 / 48)}" fill="{B.STEEL}"/>')
        vis = s * 44 / 48
    return B.svg(s, s, tile + B.mark(s / 2, s / 2, vis * ICON_FILL, f't{s}{shape}{int(bleed)}'))



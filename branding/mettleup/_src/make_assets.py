TAGLINE = 'Stronger every week.'


def hero_svg(w, h, R, cap, tag_size, uid):
    hw = R * 0.8660254
    gap = R * 0.42
    ww = B.wordmark_w(cap)
    total = 2 * hw + gap + ww
    x0 = (w - total) / 2
    mcx, mcy = x0 + hw, h / 2
    tag_cap = B.cap_of(tag_size, B.MAN_SB)
    block = cap + tag_size * 0.95 + tag_cap
    top = h / 2 - block / 2
    defs, body = B.background(w, h, uid, [(mcx, mcy, R * 2.6, 0.42), (w * 0.75, h * 1.3, w * 0.6, 0.22)],
                              lattice_mask=False)
    body += (f'<filter id="ms{uid}" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="{n(R * 0.12)}"/></filter>'
             f'<path d="{poly(B.hex_pts(mcx, mcy + R * 0.12, R))}" fill="#05060A" opacity="0.5" filter="url(#ms{uid})"/>')
    body += B.mark(mcx, mcy, R, uid + 'm')
    tx = x0 + 2 * hw + gap
    wm, _ = B.wordmark_text(tx, top + cap, cap, 'dark')
    body += wm
    d, _ = B.text_d(TAGLINE, tag_size, tx + cap * 0.02, top + cap + tag_size * 0.95 + tag_cap, B.MAN_SB, 0)
    body += f'<path d="{d}" fill="#D3D7DE"/>'
    return B.svg(w, h, f'<defs>{defs}</defs>{body}')



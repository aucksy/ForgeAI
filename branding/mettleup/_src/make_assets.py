def zoom(im, k):
    return im.resize((im.width * k, im.height * k), Image.NEAREST)


def checker(size, a='#3A3F47', b='#30343B', step=12):
    im = Image.new('RGB', size, a)
    d = ImageDraw.Draw(im)
    for y in range(0, size[1], step):
        for x in range(0, size[0], step):
            if (x // step + y // step) % 2:
                d.rectangle((x, y, x + step - 1, y + step - 1), fill=b)
    return im


class Sheet:
    def __init__(self, w):
        self.w = w
        self.items = []
        self.y = 0

    def section(self, title):
        self.items.append(('title', title))

    def row(self, tiles):
        self.items.append(('row', tiles))

    def render(self, path):
        f_t = ImageFont.truetype(os.path.join(B.LOGO.FONTS, B.MAN_XB), 34)
        f_l = ImageFont.truetype(os.path.join(B.LOGO.FONTS, B.MAN_SB), 17)
        pad = 32
        rows = []
        y = pad
        for kind, v in self.items:
            if kind == 'title':
                rows.append((kind, v, y))
                y += 64
            else:
                hmax = max(im.height for im, _ in v)
                rows.append((kind, v, y))
                y += hmax + 56
        c = Image.new('RGB', (self.w, y + pad), '#5A5F67')
        d = ImageDraw.Draw(c)
        for kind, v, yy in rows:
            if kind == 'title':
                d.text((pad, yy + 8), v, font=f_t, fill='#FFFFFF')
                d.line((pad, yy + 54, self.w - pad, yy + 54), fill='#80858D', width=2)
                continue
            x = pad
            for im, label in v:
                if im.mode == 'RGBA':
                    bgc = checker(im.size)
                    bgc.paste(im, (0, 0), im)
                    im = bgc
                c.paste(im.convert('RGB'), (x, yy))
                d.text((x, yy + im.height + 8), label, font=f_l, fill='#F0F1F3')
                x += max(im.width, int(d.textlength(label, font=f_l))) + 28
        out(B.save(c, path, 'RGB', srgb=False))
        return c



# Adaptive icon: 108 dp canvas, 72 dp shown, 66 dp safe circle (r 33 dp).
# The hex's corners sit on a 27 dp circle: 6 dp inside the safe zone, and the hex is 75 %
# of the visible tile's height, which is where Material product icons sit optically.
ADAPT_R = 27.0
ICON_FILL = ADAPT_R / 72          # hex circumradius / visible tile width, reused for full-bleed tiles


def write_ico(path, pngs):
    """ICO with PNG-compressed entries (each size rendered on its own, no resampling)."""
    blobs = []
    for im in pngs:
        import io
        b = io.BytesIO()
        im.save(b, 'PNG')
        blobs.append((im.size[0], b.getvalue()))
    head = struct.pack('<HHH', 0, 1, len(blobs))
    off = 6 + 16 * len(blobs)
    dirs, data = b'', b''
    for size, blob in blobs:
        dirs += struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(blob), off + len(data))
        data += blob
    with open(path, 'wb') as fh:
        fh.write(head + dirs + data)
    return path



#!/usr/bin/env node
/**
 * Builds src/tracker/catalog/bodyMapPaths.ts — the body drawing behind the "muscles trained"
 * map (Phase 3) — from react-native-body-highlighter 3.2.0 (MIT, (c) 2022 ELABBASSI Hicham).
 * Only the male front/back drawing data is used; the package itself is NOT a dependency.
 *
 *   npm pack react-native-body-highlighter@3.2.0 && tar -xzf react-native-body-highlighter-3.2.0.tgz
 *   node scripts/build-body-map.cjs <path-to-unpacked>/package
 *
 * The drawing has coarser regions than ForgeAI's 20 muscles, so two are split by size:
 *  - back "upper-back": the two tall wings are the lats, the small pieces on the shoulder
 *    blades are the upper back;
 *  - back "gluteal": the small top piece on each side is the outer hip (abductors), the big
 *    one the glutes.
 * Deltoids are the front shoulders on the front view and the rear shoulders on the back
 * view; side shoulders light both (see engine/bodyMap). Head, hands, knees, shins, ankles
 * and feet are drawn as plain body. Hair is left out.
 */
const fs = require('fs');
const path = require('path');
const { Resvg } = require('@resvg/resvg-js');

const pkg = process.argv[2];
if (!pkg) {
  console.error('usage: build-body-map.cjs <unpacked package dir>');
  process.exit(2);
}
const assets = path.join(pkg, 'dist', 'assets');
const front = require(path.join(assets, 'bodyFront.js')).bodyFront;
const back = require(path.join(assets, 'bodyBack.js')).bodyBack;
const wrapper = fs.readFileSync(path.join(pkg, 'dist', 'components', 'SvgMaleWrapper.js'), 'utf8');
const license = fs.readFileSync(path.join(pkg, 'LICENSE'), 'utf8').trim();
const version = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).version;

const outlines = [...wrapper.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
if (outlines.length !== 2) throw new Error(`expected 2 outlines, found ${outlines.length}`);

function bbox(d) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1448 1448" width="1448" height="1448"><path d="${d}" fill="#000"/></svg>`;
  const b = new Resvg(svg).getBBox();
  if (!b) throw new Error('empty path');
  return b;
}

const BODY = new Set(['neck', 'knees', 'tibialis', 'hands', 'ankles', 'feet', 'head']);
const FRONT = {
  chest: 'chest',
  obliques: 'obliques',
  abs: 'abs',
  biceps: 'biceps',
  triceps: 'triceps',
  trapezius: 'traps',
  deltoids: 'front_delts',
  adductors: 'adductors',
  quadriceps: 'quads',
  calves: 'calves',
  forearm: 'forearms',
};
const BACK = {
  trapezius: 'traps',
  deltoids: 'rear_delts',
  triceps: 'triceps',
  'lower-back': 'lower_back',
  forearm: 'forearms',
  adductors: 'adductors',
  hamstring: 'hamstrings',
  calves: 'calves',
};

function regionOf(view, slug, d) {
  if (BODY.has(slug)) return 'body';
  if (view === 'back' && slug === 'upper-back') return bbox(d).height > 120 ? 'lats' : 'upper_back';
  if (view === 'back' && slug === 'gluteal') return bbox(d).height < 60 ? 'abductors' : 'glutes';
  const map = view === 'front' ? FRONT : BACK;
  if (!map[slug]) throw new Error(`no region for ${view} ${slug}`);
  return map[slug];
}

function parts(view, data) {
  const out = [];
  for (const part of data) {
    if (part.slug === 'hair') continue;
    for (const side of ['left', 'right', 'common']) {
      for (const d of part.path?.[side] ?? []) out.push({ region: regionOf(view, part.slug, d), d });
    }
  }
  return out;
}

const frontParts = parts('front', front);
const backParts = parts('back', back);
const count = (list) =>
  Object.entries(list.reduce((a, p) => ((a[p.region] = (a[p.region] ?? 0) + 1), a), {}))
    .map(([k, v]) => `${k} ${v}`)
    .join(', ');
console.log('front:', count(frontParts));
console.log('back:', count(backParts));

const q = (s) => JSON.stringify(s);
const lines = [];
lines.push('/**');
lines.push(' * GENERATED by scripts/build-body-map.cjs — do not edit by hand.');
lines.push(' *');
lines.push(` * Body drawing for the "muscles trained" map (Phase 3), from react-native-body-highlighter`);
lines.push(` * ${version} (MIT). Regions are ForgeAI's finer muscles; "body" is drawn plain. Its licence`);
lines.push(' * travels with the app as BODY_MAP_LICENSE below.');
lines.push(' */');
lines.push("import type { Muscle } from './muscles';");
lines.push('');
lines.push("export type BodyRegion = Muscle | 'body';");
lines.push('');
lines.push('export interface BodyView {');
lines.push('  /** viewBox of this half of the drawing. */');
lines.push('  viewBox: { x: number; y: number; width: number; height: number };');
lines.push('  outline: string;');
lines.push('  parts: readonly { region: BodyRegion; d: string }[];');
lines.push('}');
lines.push('');
lines.push(`export const BODY_MAP_LICENSE = ${q(license)};`);
lines.push('');
for (const [name, list, x, outline] of [
  ['BODY_FRONT', frontParts, 0, outlines[0]],
  ['BODY_BACK', backParts, 724, outlines[1]],
]) {
  lines.push(`export const ${name}: BodyView = {`);
  lines.push(`  viewBox: { x: ${x}, y: 0, width: 724, height: 1448 },`);
  lines.push(`  outline: ${q(outline.replace(/\s+/g, ' ').trim())},`);
  lines.push('  parts: [');
  for (const p of list) lines.push(`    { region: ${q(p.region)}, d: ${q(p.d)} },`);
  lines.push('  ],');
  lines.push('};');
  lines.push('');
}
const outFile = path.join(__dirname, '..', 'src', 'tracker', 'catalog', 'bodyMapPaths.ts');
fs.writeFileSync(outFile, lines.join('\n'));
console.log('wrote', outFile, fs.statSync(outFile).size, 'bytes');

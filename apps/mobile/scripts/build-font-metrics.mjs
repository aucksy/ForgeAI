#!/usr/bin/env node
/**
 * Builds src/tracker/share/fontMetrics.ts — how wide each printable ASCII character is in
 * the app's fonts (in em), so the share picture (Phase 3, drawn as SVG) can cut long
 * exercise names to fit before the phone draws them.
 *
 * Measured with @resvg/resvg-js on the app's own font files: a run of 41 copies of a
 * character minus a run of 1 gives 40 advances (ink edges cancel out).
 *
 *   node scripts/build-font-metrics.mjs
 */
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { Resvg } = require('@resvg/resvg-js');

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', '..');
const fonts = join(root, 'node_modules', '@expo-google-fonts');
const fontFiles = [
  join(fonts, 'manrope', '400Regular', 'Manrope_400Regular.ttf'),
  join(fonts, 'manrope', '500Medium', 'Manrope_500Medium.ttf'),
  join(fonts, 'manrope', '600SemiBold', 'Manrope_600SemiBold.ttf'),
  join(fonts, 'manrope', '700Bold', 'Manrope_700Bold.ttf'),
  join(fonts, 'sora', '600SemiBold', 'Sora_600SemiBold.ttf'),
  join(fonts, 'sora', '700Bold', 'Sora_700Bold.ttf'),
  join(fonts, 'space-grotesk', '500Medium', 'SpaceGrotesk_500Medium.ttf'),
  join(fonts, 'space-grotesk', '700Bold', 'SpaceGrotesk_700Bold.ttf'),
];

/** Same tokens as src/tracker/share/scene.ts. */
const TOKENS = {
  display: ['Sora', 700],
  displaySemi: ['Sora', 600],
  body: ['Manrope', 400],
  bodyMedium: ['Manrope', 500],
  bodySemi: ['Manrope', 600],
  bodyBold: ['Manrope', 700],
  mono: ['Space Grotesk', 500],
  monoBold: ['Space Grotesk', 700],
};

const SIZE = 100;
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function inkWidth(family, weight, text) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="20000" height="200"><text x="10" y="150" font-family="${family}" font-weight="${weight}" font-size="${SIZE}" xml:space="preserve">${esc(text)}</text></svg>`;
  const r = new Resvg(svg, { font: { fontFiles, loadSystemFonts: false, defaultFontFamily: 'Manrope' } });
  const b = r.getBBox();
  return b ? b.width : 0;
}

/** Characters outside ASCII that the pictures use. */
const EXTRA = ['·', '×', '…', '—', '–', '→', '−', '°', '₹'];

const out = {};
const extra = {};
for (const [token, [family, weight]] of Object.entries(TOKENS)) {
  extra[token] = {};
  for (const ch of EXTRA) {
    const adv = (inkWidth(family, weight, 'H' + ch.repeat(40) + 'H') - inkWidth(family, weight, 'HH')) / 40;
    extra[token][ch] = Math.round((adv / SIZE) * 1000) / 1000;
  }
  const widths = [];
  for (let c = 32; c <= 126; c++) {
    const ch = String.fromCharCode(c);
    let adv;
    if (ch === ' ') {
      // A space has no ink: measure it between two letters.
      adv = (inkWidth(family, weight, 'H' + ' '.repeat(40) + 'H') - inkWidth(family, weight, 'HH')) / 40;
    } else {
      adv = (inkWidth(family, weight, ch.repeat(41)) - inkWidth(family, weight, ch)) / 40;
    }
    widths.push(Math.round((adv / SIZE) * 1000) / 1000);
  }
  out[token] = widths;
  console.log(token, 'avg', (widths.reduce((a, b) => a + b, 0) / widths.length).toFixed(3));
}

const lines = [
  '/**',
  ' * GENERATED by scripts/build-font-metrics.mjs — do not edit by hand.',
  ' * Advance width (in em) of each printable ASCII character, code 32 to 126, per font.',
  ' */',
  "import type { FontToken } from './scene';",
  '',
  'export const ASCII_WIDTHS: Record<FontToken, readonly number[]> = {',
  ...Object.entries(out).map(([k, v]) => `  ${k}: [${v.join(', ')}],`),
  '};',
  '',
  '/** A few characters outside ASCII the pictures use (· × … — → and the like). */',
  'export const EXTRA_WIDTHS: Record<FontToken, Readonly<Record<string, number>>> = {',
  ...Object.entries(extra).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
  '};',
  '',
];
const file = join(here, '..', 'src', 'tracker', 'share', 'fontMetrics.ts');
writeFileSync(file, lines.join('\n'));
console.log('wrote', file);
